// Generates src/text/metrics.ts: advance widths of Arimo, the metric-compatible equivalent of
// Arial (same advances by design), from @fontsource/arimo (SIL OFL 1.1). Run when updating it:
//   node scripts/generate-metrics.mjs
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const SUBSETS = ["latin", "latin-ext", "greek", "greek-ext", "cyrillic", "cyrillic-ext", "hebrew", "vietnamese"];
const dir = "node_modules/@fontsource/arimo/files";

function read(weight) {
  const widths = new Map();
  const kerning = new Map();
  let vertical;
  for (const subset of SUBSETS) {
    const buffer = readFileSync(`${dir}/arimo-${subset}-${weight}-normal.woff`);
    const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
    const upm = font.unitsPerEm;
    vertical ??= {
      ascent: font.tables.hhea.ascender / upm,
      descent: -font.tables.hhea.descender / upm,
      lineGap: font.tables.hhea.lineGap / upm,
      xHeight: font.tables.os2.sxHeight / upm,
    };
    for (const [code, index] of Object.entries(font.tables.cmap.glyphIndexMap)) {
      const cp = Number(code);
      if (cp < 32 || widths.has(cp)) continue;
      widths.set(cp, Math.round((font.glyphs.get(index).advanceWidth * 1000) / upm));
    }
    // Kerning pairs between the Latin letters, digits and punctuation of this subset
    if (subset === "latin" || subset === "latin-ext") {
      const codes = Object.keys(font.tables.cmap.glyphIndexMap)
        .map(Number)
        .filter((cp) => cp >= 32 && cp < 0x250);
      for (const a of codes) {
        for (const b of codes) {
          const value = font.getKerningValue(
            font.charToGlyph(String.fromCodePoint(a)),
            font.charToGlyph(String.fromCodePoint(b)),
          );
          const k = Math.round((value * 1000) / upm);
          if (k !== 0 && !kerning.has(`${a},${b}`)) kerning.set(`${a},${b}`, k);
        }
      }
    }
  }
  return { widths, kerning, vertical };
}

/** Kerning pairs: "aaa bbb kk" with code points and value in base 36, the value signed. */
function encodeKerning(kerning) {
  return [...kerning]
    .map(([pair, k]) => {
      const [a, b] = pair.split(",").map(Number);
      return `${a.toString(36)},${b.toString(36)},${k.toString(36)}`;
    })
    .join(";");
}

/** Runs of consecutive code points: "start:www…" with three base-36 digits per width. */
function encode(widths) {
  const codes = [...widths.keys()].sort((a, b) => a - b);
  const runs = [];
  for (const cp of codes) {
    const run = runs[runs.length - 1];
    if (run && cp === run.start + run.widths.length) run.widths.push(widths.get(cp));
    else runs.push({ start: cp, widths: [widths.get(cp)] });
  }
  return runs
    .map((r) => `${r.start.toString(36)}:${r.widths.map((w) => w.toString(36).padStart(3, "0")).join("")}`)
    .join(";");
}

const regular = read(400);
const bold = read(700);
const round = (v) => Math.round(v * 10000) / 10000;
const v = regular.vertical;
writeFileSync(
  "src/text/metrics.ts",
  `// Generated by scripts/generate-metrics.mjs from Arimo (@fontsource/arimo, SIL OFL 1.1,
// Copyright 2020 The Arimo Project Authors), whose advances match Arial's. Do not edit.
// Advances are thousandths of an em, as runs of code points: "start:www…", base 36.

export const ARIAL_REGULAR = "${encode(regular.widths)}";
export const ARIAL_BOLD = "${encode(bold.widths)}";

/** Kerning, in thousandths of an em: "left,right,value" in base 36 (browsers kern by default). */
export const ARIAL_KERNING_REGULAR = "${encodeKerning(regular.kerning)}";
export const ARIAL_KERNING_BOLD = "${encodeKerning(bold.kerning)}";

/** Vertical metrics, in ems (hhea; the same in OS/2 for this font). */
export const ARIAL_VERTICAL = { ascent: ${round(v.ascent)}, descent: ${round(v.descent)}, lineGap: ${round(v.lineGap)}, xHeight: ${round(v.xHeight)} };
`,
);
console.log(
  `regular: ${regular.widths.size} code points, ${regular.kerning.size} kerning pairs; bold: ${bold.widths.size}, ${bold.kerning.size}`,
  v,
);
